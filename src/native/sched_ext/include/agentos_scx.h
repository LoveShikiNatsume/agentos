struct agentos_task_key {
	__u32 tgid;
	__u32 pid;
};

struct agentos_task_policy_v1 {
	__u32 version;
	__u32 queue_class;
	__u32 weight;
	__u32 slice_us;
	__u32 pressure_level;
	__u32 flags;
	__u64 generation;
	__u64 updated_at_ns;
};

struct agentos_task_state_v1 {
	__u64 vtime;
	__u64 runnable_at_ns;
	__u64 running_at_ns;
	__u64 runtime_total_ns;
	__u64 wait_total_ns;
	__u64 wait_max_ns;
	__u64 dispatches;
	__u32 last_cpu;
	__u32 flags;
};

struct agentos_global_config_v1 {
	__u32 schema_version;
	__u32 flags;
	__u64 generation;
	__u64 heartbeat_ns;
	__u32 loader_pid;
	__u32 reserved;
};

_Static_assert(sizeof(struct agentos_task_key) == 8, "task key ABI changed");
_Static_assert(sizeof(struct agentos_task_policy_v1) == 40,
	       "sched_policy.v1 ABI changed");
_Static_assert(sizeof(struct agentos_task_state_v1) == 64,
	       "task state ABI changed");
_Static_assert(sizeof(struct agentos_global_config_v1) == 32,
	       "global config ABI changed");

